/// Bytes produced by a consumer adapter. They pass the same path, ownership,
/// collision, and transaction checks as manifest outputs.
class GeneratedFile {
  GeneratedFile(
    String destination,
    List<int> bytes, {
    Iterable<String> platforms = const [],
  }) : destination = relativePath(destination, output: true),
       bytes = List.unmodifiable(bytes),
       platforms = readPlatforms(platforms.toList(), present: true) {
    if (bytes.any((byte) => byte < 0 || byte > 255)) {
      throw const FormatException('Generated bytes must be in 0..255');
    }
  }

  final String destination;
  final List<int> bytes;
  final Set<String> platforms;
}

/// Builds plans without touching the project. Inputs resolve under
/// [sourceRoot], which defaults to the manifest's directory; outputs resolve
/// under [projectRoot].
class Configurator {
  Configurator({
    required String projectRoot,
    required this.manifest,
    String? sourceRoot,
  }) : projectRoot = canonicalDirectory(projectRoot),
       sourceRoot = canonicalDirectory(
         sourceRoot ?? manifest.sourceDirectory ?? Directory.current.path,
       );

  final String projectRoot;
  final String sourceRoot;
  final BrandManifest manifest;

  ConfigurationPlan plan({
    Iterable<String>? platforms,
    Map<String, Object?> overrides = const {},
    Iterable<GeneratedFile> generatedFiles = const [],
    bool overwrite = false,
  }) {
    final selected = platforms == null
        ? manifest.platforms
        : readPlatforms(platforms.toList(), present: true);
    if (!manifest.platforms.containsAll(selected) ||
        selected.isEmpty && manifest.platforms.isNotEmpty) {
      throw const FormatException('Select platforms declared by the manifest');
    }
    for (final name in overrides.keys) {
      if (!manifest.variables.containsKey(name)) {
        throw FormatException('Cannot override undeclared variable: $name');
      }
    }
    final variables = <String, Object?>{
      ...manifest.variables,
      ...stringMap(freezeValue(overrides), 'overrides'),
      'brand': manifest.brand,
    };
    final beforeState = readFile(projectRoot, statePath);
    final inventory = readInventory(beforeState);
    final desired = <GeneratedFile>[];
    bool applies(Set<String> scope) =>
        scope.isEmpty || scope.any(selected.contains);
    for (final file in manifest.files) {
      if (!applies(file.platforms)) continue;
      final source = checkedPath(sourceRoot, file.source);
      final type = FileSystemEntity.typeSync(source, followLinks: false);
      if (type == FileSystemEntityType.file) {
        final bytes = File(source).readAsBytesSync();
        desired.add(
          file.isTemplate
              ? GeneratedFile(
                  file.destination,
                  utf8.encode(renderTemplate(utf8.decode(bytes), variables)),
                  platforms: file.platforms,
                )
              : GeneratedFile(
                  file.destination,
                  bytes,
                  platforms: file.platforms,
                ),
        );
      } else if (type == FileSystemEntityType.directory && !file.isTemplate) {
        _copyTree(file.source, file.destination, file.platforms, desired);
      } else {
        throw FileSystemException('Missing or invalid input', source);
      }
    }
    for (final file in generatedFiles) {
      if (!manifest.platforms.containsAll(file.platforms)) {
        throw const FormatException('Generated file uses undeclared platforms');
      }
      if (applies(file.platforms)) desired.add(file);
    }
    if (manifest.files.isEmpty && desired.isEmpty) {
      throw const FormatException(
        'Supply manifest files or consumer-generated files',
      );
    }
    checkCollisions(desired.map((file) => file.destination));
    final nextInventory = <String, OwnedFile>{
      for (final entry in inventory.entries)
        if (!entry.value.selected(selected)) entry.key: entry.value,
    };
    checkCollisions([
      ...nextInventory.keys,
      ...desired.map((file) => file.destination),
    ]);
    final changes = <FileChange>[];
    for (final file in desired) {
      final before = readFile(projectRoot, file.destination);
      _checkOwnership(file.destination, before, inventory, overwrite);
      final beforeMode = before == null
          ? null
          : fileMode(checkedPath(projectRoot, file.destination));
      changes.add(
        FileChange(
          file.destination,
          before,
          file.bytes,
          beforeMode: beforeMode,
          afterMode: beforeMode,
        ),
      );
      nextInventory[file.destination] = OwnedFile(
        digest(file.bytes),
        file.platforms,
        manifest.brand,
      );
    }
    final destinations = desired.map((file) => file.destination).toSet();
    for (final entry in inventory.entries) {
      if (entry.value.selected(selected) && !destinations.contains(entry.key)) {
        final before = readFile(projectRoot, entry.key);
        _checkOwnership(entry.key, before, inventory, overwrite);
        changes.add(
          FileChange(
            entry.key,
            before,
            null,
            beforeMode: before == null
                ? null
                : fileMode(checkedPath(projectRoot, entry.key)),
          ),
        );
      }
    }
    changes.sort((a, b) => a.path.compareTo(b.path));
    final sortedPaths = nextInventory.keys.toList()..sort();
    final state = utf8.encode(
      '${const JsonEncoder.withIndent('  ').convert({
        'schema_version': 1,
        'files': {for (final path in sortedPaths) path: nextInventory[path]!.toJson()},
      })}\n',
    );
    return ConfigurationPlan._(
      projectRoot,
      changes,
      FileChange(statePath, beforeState, state),
    );
  }

  void _copyTree(
    String source,
    String destination,
    Set<String> platforms,
    List<GeneratedFile> output,
  ) {
    final directory = Directory(checkedPath(sourceRoot, source));
    final entries = directory.listSync(followLinks: false)
      ..sort((a, b) => a.path.compareTo(b.path));
    for (final entry in entries) {
      final name = entry.uri.pathSegments.where((part) => part.isNotEmpty).last;
      final childSource = relativePath('$source/$name');
      final childDestination = relativePath('$destination/$name', output: true);
      final path = checkedPath(sourceRoot, childSource);
      final type = FileSystemEntity.typeSync(path, followLinks: false);
      if (type == FileSystemEntityType.file) {
        output.add(
          GeneratedFile(
            childDestination,
            File(path).readAsBytesSync(),
            platforms: platforms,
          ),
        );
      } else if (type == FileSystemEntityType.directory) {
        _copyTree(childSource, childDestination, platforms, output);
      } else {
        throw FileSystemException(
          'Only regular files and directories may be copied',
          path,
        );
      }
    }
  }

  void _checkOwnership(
    String path,
    List<int>? before,
    Map<String, OwnedFile> inventory,
    bool overwrite,
  ) {
    if (overwrite || before == null) return;
    final previous = inventory[path];
    if (previous == null) {
      throw StateError(
        'Refusing to overwrite unmanaged file: $path '
        '(plan with overwrite to adopt it)',
      );
    }
    if (previous.hash != digest(before) ||
        previous.mode != null &&
            !Platform.isWindows &&
            fileMode(checkedPath(projectRoot, path)) != previous.mode) {
      throw StateError(
        'Managed file was edited: $path '
        '(keep the edits or enable overwrite)',
      );
    }
  }
}
